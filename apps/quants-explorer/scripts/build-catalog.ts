const PORTED = new Set([
  "example-orders-01-market-sma-cross",
  "example-orders-02-market-rsi-reversion",
  "example-weights-21-bollinger-reversion",
])

function figures(
  totalReturn: string | null,
  cagr: string | null,
  sharpe: string | null,
  maxDrawdown: string | null,
  winRate: string | null,
  profitFactor: string | null,
  note: string | null = null,
): Figures {
  return { totalReturn, cagr, sharpe, maxDrawdown, winRate, profitFactor, note }
}

